// Generates src/app/core/build-info-generated/build-info.generated.ts with the app version and the build date.
// The version is APP_VERSION (set by the CI from the release tag) when valid, otherwise the one in package.json.
// Runs before build, start, watch and test (npm pre-hooks). The output is not versioned.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputFile = join(root, 'src', 'app', 'core', 'build-info-generated', 'build-info.generated.ts');

const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

// Date in Italian format (dd/mm/yyyy), computed in the Italian timezone so that a build late in the evening keeps its day.
// The CI passes the release version (from the git tag vX.Y.Z) in APP_VERSION. Only a plain X.Y.Z is accepted:
// anything else (empty, malformed, with extra characters) is ignored and package.json is used, so the value
// written into the generated TypeScript file is always safe.
const envVersion = process.env.APP_VERSION?.trim();
const version = envVersion && /^\d+\.\d+\.\d+$/.test(envVersion) ? envVersion : pkg.version;
if (envVersion && version !== envVersion) {
    console.warn(`build-info: APP_VERSION ${JSON.stringify(envVersion)} is not in X.Y.Z format, using package.json version`);
}

const buildDate = new Intl.DateTimeFormat('it-IT', {
    timeZone: 'Europe/Rome',
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
}).format(new Date());

const contenuto = `// Generated by scripts/build-info.mjs. Do not edit.
export const BUILD_INFO = {
  version: ${JSON.stringify(version)},
  buildDate: ${JSON.stringify(buildDate)},
} as const;
`;

// The folder only holds this ignored file, so it does not exist in a clean checkout.
await mkdir(dirname(outputFile), { recursive: true });
await writeFile(outputFile, contenuto, 'utf8');
console.log(`build-info: version ${version}, build date ${buildDate}`);
