// Generates src/app/core/build-info.generated.ts with the app version and the build date.
// Runs before build, start, watch and test (npm pre-hooks). The output is not versioned.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputFile = join(root, 'src', 'app', 'core', 'build-info.generated.ts');

const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

// Date in Italian format (dd/mm/yyyy), computed in the Italian timezone so that a build late in the evening keeps its day.
const buildDate = new Intl.DateTimeFormat('it-IT', {
    timeZone: 'Europe/Rome',
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
}).format(new Date());

const contenuto = `// Generated by scripts/build-info.mjs. Do not edit.
export const BUILD_INFO = {
  version: ${JSON.stringify(pkg.version)},
  buildDate: ${JSON.stringify(buildDate)},
} as const;
`;

await writeFile(outputFile, contenuto, 'utf8');
console.log(`build-info: version ${pkg.version}, build date ${buildDate}`);
